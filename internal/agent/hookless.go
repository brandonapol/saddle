// HooklessEnv is set in a hookless agent's environment. The pre-commit hook
// saddle installs checks claims only when it is set (#489).
const HooklessEnv = "SADDLE_HOOKLESS"

// AllowClaimedEnv=1 lets a hookless task commit, or call done with, files
// another task claims. Saddle records each override and tells the
// orchestrator (#489).
const AllowClaimedEnv = "SADDLE_ALLOW_CLAIMED"

// advisory tells an agent saddle can't hook how its claims are checked and how to finish.
const advisory = `
## Working without saddle hooks
Saddle can't watch this agent's writes, so it checks claims when you commit
and when you call done: a commit or done that touches a file another task
claims is refused, naming the owner. A file nobody claims becomes yours when
you commit it. Edit only files under your claims; if you need anything else,
ask the owner to release it or say so in your done summary. Saddle notices
are typed into this session as lines starting with "[saddle]".
When you finish: commit everything, then run ` + "`saddle done -s \"<2-4 sentence summary>\"`" + `.
`

// hooklessPrompt is the first message for an agent with no system-prompt
// flag: the brief, the advisory rules, then the task prompt.
func hooklessPrompt(l Launch) string {
	return strings.TrimRight(l.Brief, "\n") + "\n" + advisory + "\n" + l.Prompt
}

// writeHookless writes the run dir for an agent without saddle hooks and a
// launch.sh that runs the shell line argv in the task's directory, after the
// shell lines in setup.
func (l Launch) writeHookless(name string, setup, argv []string) (string, error) {
	if err := l.record(name); err != nil {
		return "", err
	}
	for file, body := range map[string]string{"brief.md": l.Brief, "prompt.md": hooklessPrompt(l)} {
		if err := os.WriteFile(filepath.Join(l.RunDir, file), []byte(body), 0o644); err != nil {
			return "", err
		}
	}
	env := l.env()
	var sh strings.Builder
	sh.WriteString("#!/usr/bin/env bash\n# Generated by saddle. Re-run to restart this agent.\n")
	exportSaddleEnv(&sh, env)
	sh.WriteString("export " + HooklessEnv + "=1\n")
	fmt.Fprintf(&sh, "export PATH=%s:\"$PATH\"\n", l.shellPath())
	fmt.Fprintf(&sh, "cd %s || exit 1\n", shellQuote(l.Dir))
	fmt.Fprintf(&sh, "run=%s\n", shellQuote(l.RunDir))
	for _, line := range setup {
		sh.WriteString(line + "\n")
	}
	sh.WriteString(strings.Join(argv, " ") + "\n")
	fmt.Fprintf(&sh, "%s exited %s >/dev/null 2>&1\n", shellQuote(l.Bin), shellQuote(l.Task))
	sh.WriteString("echo; echo \"[saddle] agent exited. Re-run: bash $run/launch.sh\"; exec \"${SHELL:-bash}\"\n")
	launch := filepath.Join(l.RunDir, "launch.sh")
	if err := os.WriteFile(launch, []byte(sh.String()), 0o755); err != nil {
		return "", err
	}
	return "bash " + shellQuote(launch), nil
}

func (l Launch) cmdOr(def string) string {
	if l.Cmd != "" {
		return l.Cmd
	}
	return def
}

func quoteAll(args []string) []string {
	out := make([]string, len(args))
	for i, a := range args {
		out[i] = shellQuote(a)
	}
	return out
}

// hooklessInject types notices in whole, on one line: a newline would submit
// the message early.
func hooklessInject(notices string) string {
	var parts []string
	for _, line := range strings.Split(notices, "\n") {
		if line = strings.TrimSpace(line); line != "" {
			parts = append(parts, line)
		}
	}
	return "[saddle] " + strings.Join(parts, " | ")
}

// Codex is the OpenAI Codex CLI adapter: an interactive session with the
// saddle MCP server configured through -c overrides. Codex has no hooks, so
// claims are checked at commit and done (#489) and notices are typed in.
type Codex struct {
	// Home is Codex's state dir. Empty means $CODEX_HOME, then ~/.codex.
	Home string
}

func (Codex) Name() string                 { return usage.Codex }
func (Codex) Hooks() bool                  { return false }
func (Codex) Inject(notices string) string { return hooklessInject(notices) }

func (Codex) Launch(l Launch) (string, error) {
	env := l.env()
	argv := []string{shellQuote(l.cmdOr("codex"))}
	if l.Model != "" {
		argv = append(argv, "--model", shellQuote(l.Model))
	}
	argv = append(argv,
		"-c", shellQuote("mcp_servers.saddle.command="+strconv.Quote(l.Bin)),
		"-c", shellQuote(`mcp_servers.saddle.args=["mcp"]`),
		"-c", shellQuote(fmt.Sprintf("mcp_servers.saddle.env={SADDLE_ROOT=%s,SADDLE_TASK=%s}",
			strconv.Quote(env["SADDLE_ROOT"]), strconv.Quote(env["SADDLE_TASK"]))))
	argv = append(argv, quoteAll(codexApproval(l.Mode, l.Args))...)
	argv = append(argv, quoteAll(l.Args)...)
	argv = append(argv, `"$(cat "$run/prompt.md")"`)
	return l.writeHookless(usage.Codex, nil, argv)
}

// codexApproval maps a Claude permission mode to codex's approval flags
// (#480). Workers run unattended, and codex's workspace-write sandbox can't
// commit to a worktree whose git dir sits outside it, so anything but
// acceptEdits, plan or default bypasses both. Args that set approval or the
// sandbox themselves win.
func codexApproval(mode string, args []string) []string {
	for _, a := range args {
		flag, _, _ := strings.Cut(a, "=")
		switch flag {
		case "-a", "--ask-for-approval", "-s", "--sandbox", "--full-auto", "--dangerously-bypass-approvals-and-sandbox", "--yolo":
			return nil
		}
	}
	switch mode {
	case "acceptEdits":
		return []string{"--full-auto"}
	case "plan", "default":
		return nil
	}
	return []string{"--dangerously-bypass-approvals-and-sandbox"}
}

func (c Codex) Usage() UsageSource {
	return UsageSource{Agent: usage.Codex, Transcript: c.transcript}
}

// transcript is the rollout of session, which codex names
// rollout-<time>-<session>.jsonl, else the newest rollout whose session
// started in dir (#668).
func (c Codex) transcript(dir, _, session string) string {
	home := c.Home
	if home == "" {
		home = CodexHome()
	}
	var best, own string
	var bestMod time.Time
	_ = filepath.WalkDir(filepath.Join(home, "sessions"), func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasPrefix(d.Name(), "rollout-") || !strings.HasSuffix(d.Name(), ".jsonl") {
			return nil
		}
		if session != "" && strings.HasSuffix(d.Name(), "-"+session+".jsonl") {
			own = p
			return filepath.SkipAll
		}
		info, err := d.Info()
		if err != nil || !info.ModTime().After(bestMod) || rolloutCwd(p) != filepath.Clean(dir) {
			return nil
		}
		best, bestMod = p, info.ModTime()
		return nil
	})
	if own != "" {
		return own
	}
	return best
}

// rolloutCwd reads the working directory from a rollout's session_meta line.
func rolloutCwd(path string) string {
	f, err := os.Open(path)
	if err != nil {
		return ""
	}
	defer f.Close()
	buf := make([]byte, 64<<10)
	n, _ := f.Read(buf)
	first, _, _ := strings.Cut(string(buf[:n]), "\n")
	var meta struct {
		Type    string `json:"type"`
		Payload struct {
			Cwd string `json:"cwd"`
		} `json:"payload"`
	}
	if json.Unmarshal([]byte(first), &meta) != nil || meta.Type != "session_meta" || meta.Payload.Cwd == "" {
		return ""
	}
	return filepath.Clean(meta.Payload.Cwd)
}

// Gemini is the Google Gemini CLI adapter: an interactive session (-i runs
// the first message and stays open) with the saddle MCP server in a run-dir
// settings file passed as gemini's system settings. Gemini merges mcpServers
// across settings files, so the user's own servers stay. It runs no saddle
// hooks: claims are checked at commit and done (#489) and notices are typed in.
type Gemini struct{}

// GeminiName is the gemini adapter's name; usage has no gemini parser yet.
const GeminiName = "gemini"

const geminiSettings = "gemini-settings.json"

func (Gemini) Name() string                 { return GeminiName }
func (Gemini) Hooks() bool                  { return false }
func (Gemini) Inject(notices string) string { return hooklessInject(notices) }

func (Gemini) Launch(l Launch) (string, error) {
	if err := os.MkdirAll(l.RunDir, 0o755); err != nil {
		return "", err
	}
	settings := map[string]any{"mcpServers": map[string]any{
		"saddle": map[string]any{"command": l.Bin, "args": []string{"mcp"}, "env": l.env(), "trust": true},
	}}
	b, err := json.MarshalIndent(settings, "", "  ")
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(l.RunDir, geminiSettings), b, 0o644); err != nil {
		return "", err
	}
	argv := []string{shellQuote(l.cmdOr("gemini"))}
	if l.Model != "" {
		argv = append(argv, "--model", shellQuote(l.Model))
	}
	argv = append(argv, "--approval-mode", shellQuote(geminiApproval(l.Mode)), "--skip-trust")
	argv = append(argv, quoteAll(l.Args)...)
	argv = append(argv, `-i "$(cat "$run/prompt.md")"`)
	setup := []string{`export GEMINI_CLI_SYSTEM_SETTINGS_PATH="$run/` + geminiSettings + `"`}
	return l.writeHookless(GeminiName, setup, argv)
}

// geminiApproval maps a Claude permission mode to gemini's --approval-mode.
// Workers run unattended, so anything else is yolo.
func geminiApproval(mode string) string {
	switch mode {
	case "acceptEdits":
		return "auto_edit"
	case "plan", "default":
		return mode
	}
	return "yolo"
}

// Usage has no gemini transcript parser, so gemini work is not metered.
func (Gemini) Usage() UsageSource {
	return UsageSource{Agent: GeminiName, Transcript: func(string, string, string) string { return "" }}
}

// Grok is the Grok CLI adapter. Every grok worker runs the full harness: an
// interactive session in the worktree with saddle's project hooks and MCP
// server installed (see writeGrok), so it claims, spawns and calls done like
// Claude Code (#181).
type Grok struct {
	// Home is Grok's state dir. Empty means $GROK_HOME, then ~/.grok.
	Home string
}

func (Grok) Name() string         { return usage.Grok }
func (Grok) Hooks() bool          { return true }
func (Grok) Inject(string) string { return WakeLine }

func (Grok) Launch(l Launch) (string, error) {
	l.Kind = KindGrok
	return l.writeGrok()
}

func (g Grok) Usage() UsageSource {
	return UsageSource{Agent: usage.Grok, Snapshot: true, Transcript: func(dir, _, session string) string {
		return g.usageSnapshot(dir, session)
	}}
}

// usageSnapshot locates the usage ledger Grok persists for a session. The
// project directory encoding is an implementation detail, so session id is
// the durable lookup key and also handles long-path hashed directories.
func (g Grok) usageSnapshot(_ string, session string) string {
	if session == "" {
		return ""
	}
	home := g.Home
	if home == "" {
		home = os.Getenv("GROK_HOME")
	}
	if home == "" {
		h, _ := os.UserHomeDir()
		home = filepath.Join(h, ".grok")
	}
	matches, _ := filepath.Glob(filepath.Join(home, "sessions", "*", session, "usage.json"))
	if len(matches) == 0 {
		return ""
	}
	return matches[0]
}
