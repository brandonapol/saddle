package agent

import (
	"encoding/json"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
)

// openCodePlugin is the claims plugin's file in the run dir (#532).
const openCodePlugin = "saddle-claims.mjs"

// openCodePluginSrc sends each write, edit, patch and shell call to `saddle
// hook` as a PreToolUse payload, as Claude Code's hook matcher does, and
// throws when saddle denies it: opencode then fails the tool call with the
// reason. Any error running saddle lets the call through, as the hook fails
// open. The two %s are saddle's path and the task's environment, as JSON.
const openCodePluginSrc = `// Generated by saddle: enforces this task's path claims (#532).
import { spawn } from "node:child_process";

const bin = %s;
const env = %s;
const tools = new Set(["write", "edit", "multiedit", "apply_patch", "patch", "bash"]);

function hook(payload) {
  return new Promise((resolve) => {
    let out = "";
    let p;
    try {
      p = spawn(bin, ["hook"], { env: { ...process.env, ...env }, stdio: ["pipe", "pipe", "ignore"], timeout: 10000 });
    } catch {
      return resolve("");
    }
    p.stdout.on("data", (b) => (out += b));
    p.stdin.on("error", () => {});
    p.on("error", () => resolve(""));
    p.on("close", (code) => resolve(code === 0 ? out : ""));
    p.stdin.end(JSON.stringify(payload));
  });
}

export const SaddleClaims = async ({ directory }) => ({
  "tool.execute.before": async (input, output) => {
    if (!tools.has(input.tool)) return;
    const out = await hook({ hook_event_name: "PreToolUse", tool_name: input.tool, cwd: directory, tool_input: output.args ?? {} });
    let d;
    try {
      d = JSON.parse(out).hookSpecificOutput;
    } catch {
      return;
    }
    if (d && d.permissionDecision === "deny") throw new Error(d.permissionDecisionReason || "[saddle] denied");
  },
});
`

// writeOpenCodePlugin writes the claims plugin into the run dir and returns
// the file URL opencode's plugin config loads it by.
func (l Launch) writeOpenCodePlugin() (string, error) {
	bin, err := json.Marshal(l.Bin)
	if err != nil {
		return "", err
	}
	env, err := json.Marshal(l.env())
	if err != nil {
		return "", err
	}
	path, err := filepath.Abs(filepath.Join(l.RunDir, openCodePlugin))
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(path, fmt.Appendf(nil, openCodePluginSrc, bin, env), 0o644); err != nil {
		return "", err
	}
	return (&url.URL{Scheme: "file", Path: path}).String(), nil
}
